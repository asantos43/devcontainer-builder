import { podmanAdapterSh } from './podman'
import type { Settings } from './types'
export interface HelperScript {
  name: string
  text: string
  mode: number
}
export const helperNames = [
  'devcontainer-start.sh',
  'devcontainer-stop.sh',
  'devcontainer-shell.sh',
  'devcontainer-start.ps1',
  'devcontainer-stop.ps1',
  'devcontainer-shell.ps1',
]
const shQuote = (s: string) => "'" + s.replaceAll("'", "'\\''") + "'"
const psQuote = (s: string) => "'" + s.replaceAll("'", "''") + "'"
export function helperScripts(
  configPath: string,
  engine: 'docker' | 'podman',
  connection: Partial<
    Pick<Settings, 'dockerEndpoint' | 'composePath' | 'sshSocketPath' | 'tlsCertPath'>
  > = {},
): HelperScript[] {
  const environment: Record<string, string> = {}
  let address = connection.dockerEndpoint ?? ''
  if (address.startsWith('ssh://') && connection.sshSocketPath)
    address = address.replace(/\/$/, '') + connection.sshSocketPath
  if (address) {
    environment.DOCKER_HOST = address
    if (engine === 'podman') environment.CONTAINER_HOST = address
  }
  if (connection.tlsCertPath) {
    environment.DOCKER_CERT_PATH = connection.tlsCertPath
    environment.DOCKER_TLS_VERIFY = '1'
  }
  const shEnvironment = Object.entries(environment)
    .map(
      ([key, value]) =>
        'if [ -z "${' + key + ':-}" ]; then export ' + key + '=' + shQuote(value) + '; fi',
    )
    .join('\n')
  const psEnvironment = Object.entries(environment)
    .map(
      ([key, value]) => 'if (-not $env:' + key + ') { $env:' + key + ' = ' + psQuote(value) + ' }',
    )
    .join('\n')
  const composeSh = connection.composePath
    ? 'set -- --docker-compose-path ' + shQuote(connection.composePath) + ' "$@"\n'
    : ''
  const composePs = connection.composePath
    ? '--docker-compose-path ' + psQuote(connection.composePath) + ' '
    : ''

  const scripts: HelperScript[] = []
  for (const action of ['start', 'stop', 'shell'] as const) {
    const common = `#!/bin/sh\n# SPDX-License-Identifier: MPL-2.0\n# Generated by DevContainer Builder. Override DCB_ENGINE, DOCKER_HOST/CONTAINER_HOST as needed.\nset -eu\n${shEnvironment}\n# Dev Containers feature Dockerfiles are generated outside Compose build contexts.\nexport COMPOSE_BAKE=false\nexport BUILDX_BAKE_ENTITLEMENTS_FS=0\nROOT=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd -P)\nCONFIG=${shQuote(configPath)}\nENGINE=${'${DCB_ENGINE:-'}${engine}}\ncommand -v "$ENGINE" >/dev/null 2>&1 || { echo "Install $ENGINE and start its service or VM." >&2; exit 1; }\ncommand -v node >/dev/null 2>&1 || { echo 'Install Node.js and the Dev Containers CLI: npm install -g @devcontainers/cli' >&2; exit 1; }\nPROJECT=$(node -e 'process.stdout.write(require("node:crypto").createHash("sha256").update(process.argv[1]+"\\0"+process.argv[2]).digest("hex").slice(0,24))' "$ROOT" "$CONFIG")\n`
    const podmanSh = `ENGINE_PATH="$ENGINE"\nif [ "$ENGINE" = podman ]; then ENGINE_PATH="$ROOT/.devcontainer/builder-podman.sh"; export DCB_PODMAN_EVENTS_SINCE=$(node -p 'new Date().toISOString()'); fi\n`
    const cli = `command -v devcontainer >/dev/null 2>&1 || { echo 'Install the CLI: npm install -g @devcontainers/cli' >&2; exit 1; }\n`
    const body =
      action === 'start'
        ? cli +
          podmanSh +
          composeSh +
          'exec devcontainer up --workspace-folder "$ROOT" --config "$ROOT/$CONFIG" --docker-path "$ENGINE_PATH" --id-label "devcontainer-builder.project=$PROJECT" "$@"\n'
        : action === 'shell'
          ? cli +
            podmanSh +
            'if [ "$#" -eq 0 ]; then set -- /bin/sh; fi\n' +
            composeSh +
            'exec devcontainer exec --workspace-folder "$ROOT" --config "$ROOT/$CONFIG" --docker-path "$ENGINE_PATH" --id-label "devcontainer-builder.project=$PROJECT" "$@"\n'
          : `IDS=$("$ENGINE" ps -aq --filter "label=devcontainer-builder.project=$PROJECT")\nif [ -z "$IDS" ]; then echo "No managed container found."; exit 0; fi\nALL_IDS=$IDS\nfor ID in $IDS; do\n  COMPOSE=$("$ENGINE" inspect --format '{{index .Config.Labels "com.docker.compose.project"}}' "$ID")\n  FILES=$("$ENGINE" inspect --format '{{index .Config.Labels "com.docker.compose.project.config_files"}}' "$ID")\n  if [ -n "$COMPOSE" ] && [ -n "$FILES" ]; then ALL_IDS="$ALL_IDS $("$ENGINE" ps -aq --filter "label=com.docker.compose.project=$COMPOSE" --filter "label=com.docker.compose.project.config_files=$FILES")"; fi\ndone\nfor ID in $(printf '%s\\n' $ALL_IDS | sort -u); do "$ENGINE" stop "$ID"; done\n`
    scripts.push({ name: `devcontainer-${action}.sh`, text: common + body, mode: 0o755 })
    const ps = `# SPDX-License-Identifier: MPL-2.0\n# Generated by DevContainer Builder. Run with PowerShell 7+.\n$ErrorActionPreference = 'Stop'\n${psEnvironment}\n$env:COMPOSE_BAKE = 'false'\n$env:BUILDX_BAKE_ENTITLEMENTS_FS = '0'\n$Root = $PSScriptRoot\n$Config = ${psQuote(configPath)}\n$Engine = if ($env:DCB_ENGINE) { $env:DCB_ENGINE } else { ${psQuote(engine)} }\nif (-not (Get-Command $Engine -ErrorAction SilentlyContinue)) { throw "Install $Engine and start its service or VM." }\nif (-not (Get-Command node -ErrorAction SilentlyContinue)) { throw 'Install Node.js and the Dev Containers CLI: npm install -g @devcontainers/cli' }\n$Hash = [System.Security.Cryptography.SHA256]::Create()\ntry { $Bytes = $Hash.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($Root + [char]0 + $Config)); $Project = (-join ($Bytes | ForEach-Object { $_.ToString('x2') })).Substring(0, 24) } finally { $Hash.Dispose() }\n`
    const podmanPs = `$EnginePath = $Engine\n# PowerShell uses the native executable; the CLI cannot spawn .cmd adapters directly.\n`
    const psCli =
      "if (-not (Get-Command devcontainer -ErrorAction SilentlyContinue)) { throw 'Install the CLI: npm install -g @devcontainers/cli' }\n"
    const psBody =
      action === 'start'
        ? psCli +
          podmanPs +
          '& devcontainer up --workspace-folder $Root --config (Join-Path $Root $Config) --docker-path $EnginePath --id-label "devcontainer-builder.project=$Project" ' +
          composePs +
          '@args\nexit $LASTEXITCODE\n'
        : action === 'shell'
          ? psCli +
            podmanPs +
            '$CommandArgs = if ($args.Count) { $args } else { @(\'/bin/sh\') }\n& devcontainer exec --workspace-folder $Root --config (Join-Path $Root $Config) --docker-path $EnginePath --id-label "devcontainer-builder.project=$Project" ' +
            composePs +
            '@CommandArgs\nexit $LASTEXITCODE\n'
          : `$Ids = @(& $Engine ps -aq --filter "label=devcontainer-builder.project=$Project")\nif ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }\nforeach ($Id in $Ids) {\n  $LabelsJson = & $Engine inspect --format '{{json .Config.Labels}}' $Id\n  if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE }\n  $Labels = $LabelsJson | ConvertFrom-Json\n  $Compose = $Labels.'com.docker.compose.project'\n  $Files = $Labels.'com.docker.compose.project.config_files'\n  if ($Compose -and $Files) { $Ids += @(& $Engine ps -aq --filter "label=com.docker.compose.project=$Compose" --filter "label=com.docker.compose.project.config_files=$Files") }\n}\nforeach ($Id in ($Ids | Sort-Object -Unique)) { & $Engine stop $Id; if ($LASTEXITCODE -ne 0) { exit $LASTEXITCODE } }\n`
    scripts.push({ name: `devcontainer-${action}.ps1`, text: ps + psBody, mode: 0o644 })
  }
  scripts.push({ name: '.devcontainer/builder-podman.sh', text: podmanAdapterSh, mode: 0o755 })
  return scripts
}
